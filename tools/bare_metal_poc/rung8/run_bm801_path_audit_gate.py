# ---------------------------------------------------------------- hand-derived wants
def want_px(rows, w, h, cw, ch, p, r, c, x, y, rgb=False):
    """One pixel of logical cell (r,c): relabel, then phase, then mode. By hand."""
    pr, pc = (r + p['ko']) % vga.ROWS, (c + p['jo']) % vga.COLS
    y0, x0 = pr * ch + p['dy'], pc * cw + p['dx']
    if not (y0 >= 0 and y0 + ch <= h and x0 >= 0 and x0 + cw <= w) and p['mode'] == 'clamp':
        return (0, 0, 0) if rgb else 0
    px = rows[(y0 + y) % h][(x0 + x) % w]
    return (px[0], px[1], px[2]) if rgb else sum(px)


def want_cell(rows, w, h, cw, ch, p, r, c):
    return [[want_px(rows, w, h, cw, ch, p, r, c, x, y) for x in range(cw)]
            for y in range(ch)]


def want_raw(rows, w, h, cw, ch, p, r, c):
    return [want_px(rows, w, h, cw, ch, p, r, c, x, y, rgb=True)
            for y in range(ch) for x in range(cw)]


def want_plane(rows, w, h, cw, ch, p, r, c):
    g = want_cell(rows, w, h, cw, ch, p, r, c)
    flat = [v for row in g for v in row]
    if max(flat) - min(flat) < vga.FLAT_SPAN:
        return tuple([0] * (cw * ch)), True
    mid = (min(flat) + max(flat)) / 2.0
    m = [[1 if v > mid else 0 for v in row] for row in g]
    corners = [m[0][0], m[0][cw - 1], m[ch - 1][0], m[ch - 1][cw - 1]]
    if sum(corners) * 2 > len(corners):
        m = [[1 - v for v in row] for row in m]
    return tuple(v for row in m for v in row), False


def want_profile(rows, w, h, cw, ch, p):
    prof = [0] * cw
    for r in range(vga.ROWS):
        for c in range(vga.COLS):
            g = want_cell(rows, w, h, cw, ch, p, r, c)
            for x in range(cw):
                col = [g[y][x] for y in range(ch)]
                prof[x] += max(col) - min(col)
    return prof


def want_in_frame(w, h, cw, ch, p, r, c):
    pr, pc = (r + p['ko']) % vga.ROWS, (c + p['jo']) % vga.COLS
    y0, x0 = pr * ch + p['dy'], pc * cw + p['dx']
    return y0 >= 0 and y0 + ch <= h and x0 >= 0 and x0 + cw <= w


