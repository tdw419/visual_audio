"""tools/pyshader_hart.py — PS010 rung 1: two-hart mailbox, host-driven.

SKELETON (skeleton-driven-development): interfaces LOCKED, bodies
stubbed. Spec: GPU_CPU_EMULATOR_ROADMAP.md PS010 section (:221-334);
builder contract: .builder_queue/brief_ps010_two_hart_mailbox.md.
The builder populates ONE stub per run; each stub's gate clause lives in
the brief's step table. If a signature below looks wrong, file
REPAIR_PENDING_ps010_<topic>.md — do NOT edit this file's interfaces.

Model (the roadmap's "host-driven rounds" shape, per-hart execution via
the PS008 control layer — NO GPU legs in rung 1):

    hart A (writer) ─┐
                     ├─ each round: every live hart executes up to
    hart B (spinner)─┘  steps_per_round transitions against its OWN
                        double-buffered dmem copy, then hart buffers are
                        WRITE-MERGED in round order (not final-state).

Inter-hart state is visible only at round boundaries — an honest,
documented narrowing vs QEMU SMP interleaving (roadmap :225-228).
sync="single" runs both harts on ONE shared dmem with no per-round
copies: the deliberate race variant, used by the RED leg to prove the
sync recipe is load-bearing (roadmap gate :229-231).

Mailbox word layout (dmem, words): dmem[0] = flag+payload (A writes 1),
dmem[1] = A's pin record (7), dmem[2] = sentinel (123, never written).

Hand-computed pin (author, 2026-09-20 — re-derive before step 1 GREEN;
steps counted per the PS008 run_ctl_trace convention: EBREAK halts
WITHOUT counting as a transition):
A: 6 transitions (2 ADDI, SW, ADDI, SW, JAL — poison at insn 6 SKIPPED;
   EBREAK at insn 7 halts uncounted). Final A regs: x1=7, x9=1, x10=0,
   x31=0 (poison value 99 never lands).
B: 6 transitions. Rounds 1-2: ADDI, then LW sees flag=0 (A's round-3 SW
   becomes visible to B only at the round-4 boundary). Round 3: BEQ
   taken (back to insn 1). Round 4: LW AGAIN (pc=1), now sees flag=1.
   Round 5: BEQ not-taken, falls through. Round 6: ADDI x6 = 1+6 = 7.
   Round 7: EBREAK halts. Final B regs: x5=1, x6=7, x10=0.
   (steps_b was pinned 5 until RULING_ps010_steps_b_pin.md: the
   original trace dropped B's round-4 spin re-read of the LW.)
Rounds to completion: 7 (A's EBREAK lands in round 7; rounds = max over
   harts of the round in which the hart halted).
Final dmem: [1, 7, 123, 0, 0, 0, 0, 0].

What the stubs return is deliberate: run_two_hart raises
NotImplementedError (silence would be dangerous); the pins above are
asserted by the behavioral tests.
"""
