# ── per-hart block layout ───────────────────────────────────────────────
PC_OFF = 32
RUNNING_OFF = 33
STOP_OFF = 34
NINSN_OFF = 35
IMEMBASE_OFF = 36
HART_BLOCK_WORDS = 37

WG_SIZE = 64                    # invocations per workgroup

STOP_NONE = 0
STOP_IMEM_OOB = 2
STOP_BAD_OPCODE = 3

EBREAK_WORD = 0x00100073

# Buffer cap: 65536 harts * 37 + programs. Guard, not a tuning knob.
MAX_TOTAL_WORDS = 65536 * HART_BLOCK_WORDS + 65536 * 8

_SHADER_HEADER = """// generated by tools/pyshader_multihart.py — PS010c N-hart kernel
@group(0) @binding(0) var<storage, read_write> buf: array<u32, %(ARRAY_WORDS)u>;

// GENERATED step_r / step_i bodies (tools.pyshader_rvexec.STEP_*_SRC
// via _alu_body_wgsl — the PS006 extraction, unmodified; the PS009a
// seam reused verbatim).
fn step_r(r1: u32, r2: u32, r3: u32, r4: u32) -> u32 {
    var r0: u32 = 0u;
%(STEP_R_DECLS)s
%(STEP_R_BODY)s
}
fn step_i(r1: u32, r2: u32, r3: u32, r4: u32) -> u32 {
    var r0: u32 = 0u;
%(STEP_I_DECLS)s
%(STEP_I_BODY)s
}

@compute @workgroup_size(%(WG_SIZE)u, 1, 1)
fn main(@builtin(global_invocation_id) gid: vec3<u32>) {
    let hart = gid.x;
    if (hart >= buf[0u]) { return; }   // buf[0] = nharts (pinned prefix)
    let b = %(HART_BLOCK)su + hart * %(STRIDE)u;
    if (buf[b + %(RUNNING)su] == 0u) { return; }   // halted harts idle
    let base = buf[b + %(IMEMBASE)su];
    let ninsn = buf[b + %(NINSN)su];
    let pc = buf[b + %(PC)su];
    if (pc >= ninsn) {
        buf[b + %(STOP)su] = %(STOP_IMEM_OOB_C)su;
        buf[b + %(RUNNING)su] = 0u;
        return;
    }
    let word = buf[base + pc];
    let opcode = word & 127u;
    let rd = (word >> 7u) & 31u;
    let funct3 = (word >> 12u) & 7u;
    let rs1 = (word >> 15u) & 31u;
    let rs2 = (word >> 20u) & 31u;
    let funct7 = (word >> 25u) & 127u;

    if (word == %(EBREAK)su) {
        // EBREAK halts UNCOUNTED (PS008): no transition committed.
        buf[b + %(RUNNING)su] = 0u;
        return;
    }
    if (opcode == 99u) {
        // All six B-type funct3 (RULING_ps010c_blt_in_divergent_prog:
        // semantics verbatim from the LOCKED host oracle ref_ctl,
        // tools/pyshader_ctl.py — BEQ eq, BNE ne, BLT/BGE signed,
        // BLTU/BGEU unsigned). funct3 2/3 = STOP_BAD_OPCODE.
        // SPEC: target = pc + imm//4 (RULING_ps008_branch_convention).
        if (funct3 == 2u || funct3 == 3u) {
            buf[b + %(STOP)su] = %(STOP_BAD_OPCODE_C)su;
            buf[b + %(RUNNING)su] = 0u;
            return;
        }
        let imm = ((word >> 31u) & 1u) * 4096u
                + ((word >> 7u) & 1u) * 2048u
                + ((word >> 25u) & 63u) * 32u
                + ((word >> 8u) & 15u) * 2u;
        let signed_imm = i32(imm ^ 4096u) - 4096;
        let a = buf[b + rs1];
        let bval = buf[b + rs2];
        let eq = a == bval;
        // u32-vs-u32 compare IS the unsigned compare (BLTU/BGEU);
        // i32 reinterpretation IS the signed compare (BLT/BGE) —
        // exactly ref_ctl's _signed_lt.
        let slt = i32(a) < i32(bval);
        var taken = false;
        if (funct3 == 0u) { taken = eq; }           // BEQ
        if (funct3 == 1u) { taken = !eq; }          // BNE
        if (funct3 == 4u) { taken = slt; }          // BLT
        if (funct3 == 5u) { taken = !slt; }         // BGE
        if (funct3 == 6u) { taken = a < bval; }     // BLTU
        if (funct3 == 7u) { taken = a >= bval; }    // BGEU
        var npc = pc + 1u;
        if (taken) {
            npc = (pc * 4u + u32(signed_imm)) / 4u;
        }
        buf[b + %(PC)su] = npc;   // one transition per dispatch
        return;
    }
    if (opcode == 51u) {
        let result = step_r(funct3, funct7, buf[b + rs1], buf[b + rs2]);
        if (rd != 0u) { buf[b + rd] = result; }
        buf[b + %(PC)su] = pc + 1u;
        return;
    }
    if (opcode == 19u) {
        let imm_i = (word >> 20u) & 4095u;
        let simm = i32(imm_i ^ 2048u) - 2048;
        let result = step_i(funct3, funct7, buf[b + rs1], u32(simm));
        if (rd != 0u) { buf[b + rd] = result; }
        buf[b + %(PC)su] = pc + 1u;
        return;
    }
    buf[b + %(STOP)su] = %(STOP_BAD_OPCODE_C)su;
    buf[b + %(RUNNING)su] = 0u;
}
"""

# Programs for gate legs (LOCKED texts imported; words via _words()).
GATE_LEGS = ("uniform", "static_mix", "adversarial")
GATE_NS = (2, 8, 64, 4096, 65536)


def _words(asm_text: str) -> List[int]:
    from tools.rv32i_asm import assemble
    b = assemble(asm_text)
    return [int.from_bytes(b[i:i + 4], "little")
            for i in range(0, len(b), 4)]


