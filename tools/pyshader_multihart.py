"""tools/pyshader_multihart.py — PS010c rung: N-hart GPU kernel, correctness.

SKELETON (skeleton-driven-development): interfaces LOCKED, bodies
stubbed. Spec: GPU_CPU_EMULATOR_ROADMAP.md:233-310 + the PS010b step-4
CORRECTION (.builder_queue/brief_ps010b_divergence_sweep.md — the host
proxy is scale-invariant, so the divergence verdict needs a leg whose
numbers can move); builder contract:
.builder_queue/brief_ps010c_gpu_multihart.md.
The builder populates ONE stub per run; each stub's gate clause lives in
the brief's step table. If a signature below looks wrong, file
REPAIR_PENDING_ps010c_<topic>.md — do NOT edit this file's interfaces.

Model (the PS009a seam extended to N harts, PS010b round semantics):
one storage buffer, one block per hart; the shader's main() runs one
invocation per hart (dispatch_workgroups(ceil(N/WG),1,1)); each
invocation executes EXACTLY ONE transition per dispatch (the round
model — inter-hart state visible only at boundaries; the programs here
are dmem-free so harts are independent and parity is bit-for-bit).
The host loops dispatches (rounds) until every hart is halted
(running==0), or max_rounds is exhausted (loud RuntimeError).

Per-hart block layout (u32 words, HART_BLOCK_WORDS stride):
    [0..31]  registers
    [32]     pc (instruction index)
    [33]     running (1 while live)
    [34]     stop (0 running / 2 IMEM_OOB / 3 BAD_OPCODE)
    [35]     ninsn (per-hart imem length)
    [36]     imem_base (word index of this hart's program start)
imem is appended after all N blocks (static-mix leg packs two programs;
per-hart imem_base points at the hart's own copy — no aliasing).

Instruction subset == PS009a's, plus EBREAK halt:
    R-type 0x33 (ALU funct3 0/1/4/5/6/7) via GENERATED step_r body,
    ALU-Imm 0x13 via GENERATED step_i body,
    B-type 0x63, all six funct3 (BEQ/BNE/BLT/BGE/BLTU/BGEU, RULING_ps010c_
    blt_in_divergent_prog), SPEC semantics target = pc + imm//4
    (RULING_ps008_branch_convention); EBREAK 0x00100073 halts UNCOUNTED
    (running=0, no transition committed — the PS008 convention).
Anything else = STOP_BAD_OPCODE. IMEM_OOB is a per-hart fault surfaced
in the receipt's stop list, never swallowed.

Honest boundary (MIRRORED from PS009a, still true here): no performance
claim anywhere in this rung. wall_seconds are recorded because they are
free; the uniform-vs-adversarial comparison that answers roadmap
:246-268 is the MEASUREMENT rung (same-process pairing, floors
attached), not this correctness gate.

What the stubs return is deliberate: they raise NotImplementedError
(silence would be dangerous); the pins are asserted by the behavioral
tests.
"""
