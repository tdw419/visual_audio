def vga_row_to_pixels(row_bits: int) -> np.ndarray:
    """Convert an 8-bit VGA font row to pixel array (8 pixels)."""
    return np.array([255 if (row_bits >> bit) & 1 else 0 for bit in range(7, -1, -1)], dtype=np.uint8)


def vga_glyph_to_bitmap(glyph_data: List[int]) -> np.ndarray:
    """Convert VGA font glyph data (16 rows) to 8x16 bitmap."""
    return np.array([vga_row_to_pixels(row) for row in glyph_data], dtype=np.uint8)


def get_vga_bitmap(char: str) -> np.ndarray:
    """Get the 8x16 bitmap for a character."""
    if char not in VGA_FONT_8X16:
        # Return empty bitmap for unknown characters
        return np.zeros((16, 8), dtype=np.uint8)
    return vga_glyph_to_bitmap(VGA_FONT_8X16[char])


def render_text_with_vga_font(text: str, width: int = 800, height: int = 600,
                               x: int = 0, y: int = 0) -> 'Image.Image':
    """Render text using VGA 8x16 bitmaps (pixel-perfect, no anti-aliasing)."""
    from PIL import Image
    
    img = Image.new('L', (width, height), 0)
    pixels = np.array(img)
    
    cursor_x = x
    for char in text:
        if char == '\n':
            cursor_x = x
            y += 16
            continue
        
        bitmap = get_vga_bitmap(char)
        
        # Blit bitmap using np.maximum to support overlapping
        if y + 16 <= height and cursor_x + 8 <= width:
            pixels[y:y+16, cursor_x:cursor_x+8] = np.maximum(
                pixels[y:y+16, cursor_x:cursor_x+8], bitmap
            )
        
        cursor_x += 8
    
    return Image.fromarray(pixels)


