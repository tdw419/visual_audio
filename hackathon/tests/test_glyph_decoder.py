"""h3 — SAM 3.1 glyph decoder, OFFLINE ground-truth tests.

Zero network: the decoder under test is pure (no transport object exists);
the meta client import used by h2 is deliberately not touched here. If any
code under test ever grows network access, h2's module-level closed-port pin
pattern should be replicated here.

Fixture set (committed ground truth, generated by hackathon/demo/glyph_poster.py):
  glyph_poster_gt.png     poster image, payload encoded in Hilbert-mapped cells
  glyph_poster_gt.json    canonical frame + expected payload bytes + md5s
  glyph_response_gt.json  SAM-3.1-shaped recorded segmentation response
  sam_response_red_rect.json  the 2026-10-26 LIVE probe (parser wire-shape test)
"""
import hashlib
import json
import pathlib

import pytest

FIXTURES = pathlib.Path(__file__).resolve().parent / "fixtures"


def _fixture(name):
    return json.loads((FIXTURES / name).read_text())


@pytest.fixture(scope="module")
def glyph_decoder():
    from hackathon.demo import glyph_decoder

    return glyph_decoder


@pytest.fixture(scope="module")
def gt():
    return _fixture("glyph_poster_gt.json")


def test_parses_live_sam_wire_shape(glyph_decoder):
    """Parser must handle the REAL live probe stream (2026-10-26 receipt)."""
    live = _fixture("sam_response_red_rect.json")
    text = live["output"][0]["content"][0]["text"]
    parsed = glyph_decoder.parse_sam_stream(text)
    assert parsed["prefix"] == "<0f>0"
    assert len(parsed["boxes"]) == 1
    box = parsed["boxes"][0]
    assert (box["x1"], box["y1"], box["x2"], box["y2"]) == (60, 260, 220, 330)
    assert (box["w"], box["h"]) == (640, 400)
    assert len(parsed["masks"]) == 1
    assert parsed["masks"][0]["x"] == 0 and parsed["masks"][0]["y"] == 0
    assert len(parsed["masks"][0]["data"]) > 0


def test_decode_ground_truth_byte_identical(glyph_decoder, gt):
    """Decode the recorded response; payload must byte-match ground truth."""
    response = _fixture("glyph_response_gt.json")
    payload = glyph_decoder.decode_poster_response(response)
    assert isinstance(payload, bytes)
    assert payload.hex() == gt["payload_hex"]
    assert hashlib.md5(payload).hexdigest() == gt["payload_md5"]


def test_decode_is_deterministic(glyph_decoder, gt):
    response = _fixture("glyph_response_gt.json")
    runs = [glyph_decoder.decode_poster_response(response) for _ in range(3)]
    assert runs[0] == runs[1] == runs[2]
    assert hashlib.md5(runs[0]).hexdigest() == gt["payload_md5"]


def test_decode_rejects_wrong_magic(glyph_decoder):
    bad = _fixture("glyph_response_gt.json")
    text = bad["output"][0]["content"][0]["text"]
    # Flip one filled cell's bit by swapping an RLE pair boundary: replace the
    # first ",1" run with ",0" so the framed magic goes invalid.
    tampered = text.replace(",1,", ",0,", 1)
    bad["output"][0]["content"][0]["text"] = tampered
    with pytest.raises(glyph_decoder.DecodeError):
        glyph_decoder.decode_poster_response(bad)


def test_poster_generator_matches_committed_png(gt):
    """The committed poster PNG is exactly what the generator produces."""
    from hackathon.demo import glyph_poster

    payload = bytes.fromhex(gt["payload_hex"])
    grid = glyph_poster.payload_to_cells(payload)
    png = glyph_poster.png_bytes(grid)
    assert hashlib.md5(png).hexdigest() == gt["poster_png_md5"]
    committed = (FIXTURES / "glyph_poster_gt.png").read_bytes()
    assert hashlib.md5(committed).hexdigest() == gt["poster_png_md5"]


def test_frame_dimensions_enforced(glyph_decoder, gt):
    """One canonical spatial frame: box w/h must equal the canonical frame."""
    response = _fixture("glyph_response_gt.json")
    text = response["output"][0]["content"][0]["text"]
    drifted = text.replace("w=512;h=512", "w=640;h=400")
    response["output"][0]["content"][0]["text"] = drifted
    with pytest.raises(glyph_decoder.DecodeError):
        glyph_decoder.decode_poster_response(response)
