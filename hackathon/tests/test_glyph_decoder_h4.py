"""h4 — decoder robustness: stylized posters, point prompts, classical fallback.

Zero network, fixtures only (ticket constraint: no live SAM calls in lane
verify). The classical fallback path decodes the poster PNG pixels directly
(pure-stdlib PNG reader + Otsu threshold + per-cell mean vote).

Fixtures (generated by hackathon/demo/glyph_fixtures_h4.py, committed):
  glyph_poster_stylized.png/.json + glyph_response_stylized.json
      UNSEEN payload, stylized canvas (nonzero box origin, decorative border,
      non-pure ink/background), promptable point token, wire score = the
      MEASURED Otsu separability (eta) of the poster.
  glyph_poster_lowconf.png/.json + glyph_response_lowconf.json
      degraded poster whose measured eta lands BELOW the committed
      CONF_THRESHOLD; the response wire score (= measured eta) must trip the
      classical fallback and the pixels alone must still decode
      byte-identically.
  h4_calibration.md — the measured sweep behind CONF_THRESHOLD.
"""
import hashlib
import json
import pathlib

import pytest

FIXTURES = pathlib.Path(__file__).resolve().parent / "fixtures"
CONF_THRESHOLD = 0.90


def _fixture(name):
    return json.loads((FIXTURES / name).read_text())


def _response(text):
    return {
        "output": [
            {
                "type": "message",
                "role": "assistant",
                "content": [{"type": "output_text", "text": text}],
            }
        ]
    }


@pytest.fixture(scope="module")
def glyph_decoder():
    from hackathon.demo import glyph_decoder

    return glyph_decoder


# --------------------------------------------------------------- parsing ---


def test_point_and_score_tokens_parsed(glyph_decoder):
    """Promptable points and confidence score tokens parse out of the stream."""
    res = _fixture("glyph_response_stylized.json")
    parsed = glyph_decoder.parse_sam_stream(res["output"][0]["content"][0]["text"])
    assert parsed["points"] == [{"x": 300, "y": 300, "label": 1}]
    assert parsed["score"] == pytest.approx(_fixture("glyph_poster_stylized.json")["wire_score"], abs=5e-4)
    assert len(parsed["boxes"]) == 1


# ------------------------------------------------- multi-box point select ---


def test_multibox_point_selects_box(glyph_decoder):
    """With 2 boxes, the promptable point must select WHICH box decodes."""
    from hackathon.demo import glyph_poster

    pa = b"alpha-box payload selected by the point prompt"
    pb = b"beta-box payload that must NOT be selected"
    text = (
        "<0f>0"
        "<|point;x=100;y=100;label=1|>"
        "<|box;x1=0;y1=0;x2=512;y2=512;w=512;h=512|>"
        "<|mask;x=0;y=0;data="
        + glyph_poster.cells_to_rle(glyph_poster.payload_to_cells(pa))
        + "|>"
        "<|box;x1=512;y1=512;x2=1024;y2=1024;w=512;h=512|>"
        "<|mask;x=0;y=0;data="
        + glyph_poster.cells_to_rle(glyph_poster.payload_to_cells(pb))
        + "|>"
    )
    out = glyph_decoder.decode_poster_auto(_response(text))
    assert out["payload"] == pa
    assert out["path"] == "sam"


def test_multibox_without_point_raises(glyph_decoder):
    """Ambiguous multi-box stream with NO point must raise, not guess."""
    from hackathon.demo import glyph_poster

    rle = glyph_poster.cells_to_rle(glyph_poster.payload_to_cells(b"payload"))
    text = (
        "<0f>0"
        "<|box;x1=0;y1=0;x2=512;y2=512;w=512;h=512|>"
        "<|mask;x=0;y=0;data=" + rle + "|>"
        "<|box;x1=512;y1=512;x2=1024;y2=1024;w=512;h=512|>"
        "<|mask;x=0;y=0;data=" + rle + "|>"
    )
    with pytest.raises(glyph_decoder.DecodeError):
        glyph_decoder.decode_poster_auto(_response(text))


# ------------------------------------------------------- stylized poster ---


def test_stylized_sam_path_byte_identical(glyph_decoder):
    """Unseen stylized poster: SAM path (score >= threshold) decodes exactly."""
    st = _fixture("glyph_poster_stylized.json")
    res = _fixture("glyph_response_stylized.json")
    out = glyph_decoder.decode_poster_auto(res)
    assert out["path"] == "sam"
    assert out["confidence"] >= CONF_THRESHOLD
    assert out["payload"].hex() == st["payload_hex"]
    assert hashlib.md5(out["payload"]).hexdigest() == st["payload_md5"]


def test_confidence_gate_is_measured_not_vibes(glyph_decoder):
    """Wire score in the fixtures IS the measured Otsu eta of the poster,
    recomputed live from the committed PNGs — clean above, degraded below."""
    st = _fixture("glyph_poster_stylized.json")
    lo = _fixture("glyph_poster_lowconf.json")
    assert st["otsu_eta"] >= CONF_THRESHOLD
    assert lo["otsu_eta"] < CONF_THRESHOLD
    assert float(lo["wire_score"]) == pytest.approx(lo["otsu_eta"], abs=5e-4)

    rows = glyph_decoder.read_gray_png((FIXTURES / "glyph_poster_stylized.png").read_bytes())
    b = st["box"]
    crop = [r[b["x1"]:b["x2"]] for r in rows[b["y1"]:b["y2"]]]
    _, eta = glyph_decoder.otsu(crop)
    assert eta == pytest.approx(st["otsu_eta"], abs=1e-9)


# ---------------------------------------------------- classical fallback ---


def test_fallback_trips_and_decodes_byte_identical(glyph_decoder):
    """Low-confidence fixture: fallback path chosen, pixels alone decode."""
    lo = _fixture("glyph_poster_lowconf.json")
    png = (FIXTURES / "glyph_poster_lowconf.png").read_bytes()
    res = _fixture("glyph_response_lowconf.json")
    out = glyph_decoder.decode_poster_auto(res, poster_png=png)
    assert out["path"] == "pixels"
    assert out["confidence"] < CONF_THRESHOLD
    assert out["payload"].hex() == lo["payload_hex"]
    assert hashlib.md5(out["payload"]).hexdigest() == lo["payload_md5"]


def test_fallback_requires_png(glyph_decoder):
    """Low-confidence response with no poster PNG cannot fall back."""
    res = _fixture("glyph_response_lowconf.json")
    with pytest.raises(glyph_decoder.DecodeError):
        glyph_decoder.decode_poster_auto(res)


def test_classical_pixel_decode_canonical(glyph_decoder):
    """Pure classical path on the canonical h3 poster: byte-identical, high eta."""
    gt = _fixture("glyph_poster_gt.json")
    payload, eta = glyph_decoder.decode_poster_pixels((FIXTURES / "glyph_poster_gt.png").read_bytes())
    assert payload.hex() == gt["payload_hex"]
    assert eta >= CONF_THRESHOLD


# ------------------------------------------------------------ png reader ---


def test_read_gray_png_dims_and_content(glyph_decoder):
    rows = glyph_decoder.read_gray_png((FIXTURES / "glyph_poster_gt.png").read_bytes())
    assert len(rows) == 512
    assert len(rows[0]) == 512
    assert rows[0][0] == 0xFF            # background corner
    assert min(min(r) for r in rows) == 0x00  # ink present


# ------------------------------------------------- fixture regeneration ---


def test_h4_fixture_regeneration_tie(tmp_path):
    """Committed fixtures are exactly what the committed generator emits."""
    from hackathon.demo import glyph_fixtures_h4 as gen

    gen.build_all(tmp_path)
    names = [
        "glyph_poster_stylized.png", "glyph_poster_stylized.json",
        "glyph_response_stylized.json",
        "glyph_poster_lowconf.png", "glyph_poster_lowconf.json",
        "glyph_response_lowconf.json",
        "h4_calibration.md",
    ]
    for name in names:
        a = hashlib.md5((tmp_path / name).read_bytes()).hexdigest()
        b = hashlib.md5((FIXTURES / name).read_bytes()).hexdigest()
        assert a == b, f"{name} does not regenerate byte-identically"
