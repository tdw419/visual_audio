def test_fixtures_regenerate_byte_identically(corpus):
    """Committed corpus fixtures are generator output, not hand-written:
    rerunning glyph_fixtures_h5.py reproduces them byte-for-byte."""
    import shutil
    if shutil.which("riscv64-unknown-elf-gcc") is None:
        pytest.skip("riscv64-unknown-elf-gcc not installed")
    import tempfile
    from hackathon.demo import glyph_fixtures_h5
    with tempfile.TemporaryDirectory() as td:
        glyph_fixtures_h5.main(td)
        regen = json.loads((pathlib.Path(td) / "h5_corpus.json").read_text())
    assert regen["cases"] == corpus["cases"]
