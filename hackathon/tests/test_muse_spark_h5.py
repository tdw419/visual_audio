"""h5 — Muse Spark semantic layer v1: description -> glyph asm -> canvas.

Offline only (lane constraint: Meta API calls are fixtures; live probes are
operator receipts; no GPU, no boot). Corpus ground truth is the committed
h5_corpus.json fixture set generated by hackathon/demo/glyph_fixtures_h5.py:
English description + transpiler reference asm + measured ground truth
(native x86 == GlyphCPUv2 r10, the corpus's QEMU-diff-verified engine chain).

Glyph asm conventions enforced here (grounded in tools/glyph_isa_v2.py):
  - operands are space-separated (assembler splits on whitespace)
  - a label def (":name") is the SOLE token on its line (BK-315 pass 1)
  - JNZ/JZ are flag-based: JZ jumps when the CMP flag r0 is set, JNZ when
    it is clear (SE024 complement pair) — never a direct operand compare
  - a 3rd arithmetic operand is SILENTLY DROPPED at the machine level
    (BK-315 accumulator class: ADD r1 r1 5 ran wrong for three tickets)
"""
import json
import pathlib

import pytest

FIXTURES = pathlib.Path(__file__).resolve().parent / "fixtures"


def _fixture(name):
    return (FIXTURES / name).read_text()


def _fixture_json(name):
    return json.loads(_fixture(name))


def _client_factory(module, calls):
    """MetaClient wired to a recording fake transport (zero network)."""

    def fake_transport(request):
        calls.append(request.full_url)
        return 200, json.dumps(_fixture_json("h5_response_sum_match.json")).encode()

    from hackathon.demo import meta_client
    return meta_client.MetaClient(
        base_url="http://127.0.0.1:9/", api_key="test-key",
        transport=fake_transport)


@pytest.fixture(scope="module")
def muse():
    from hackathon.demo import muse_spark
    return muse_spark


@pytest.fixture(scope="module")
def corpus():
    return _fixture_json("h5_corpus.json")


# ------------------------------------------------------------ conventions ---

def test_prompt_embeds_all_four_conventions(muse):
    """The builder prompt must name every convention the machine enforces."""
    prompt = muse.build_prompt("Sum 1 through 10.")
    text = json.dumps(prompt)
    assert "space-separated" in text
    assert "3rd" in text or "third" in text
    assert "SILENTLY DROPPED" in text
    assert "JNZ" in text and "flag" in text.lower()
    assert "label" in text.lower()


def test_lint_rejects_third_arith_operand(muse):
    res = _fixture_json("h5_response_bad3op.json")
    asm = muse.extract_asm(res["choices"][0]["message"]["content"])
    with pytest.raises(muse.MuseAsmError) as ei:
        muse.lint_asm(asm)
    assert "3rd" in str(ei.value) or "third" in str(ei.value) or "arity" in str(ei.value)


def test_lint_rejects_label_glued_to_instruction(muse):
    res = _fixture_json("h5_response_badlabel.json")
    asm = muse.extract_asm(res["choices"][0]["message"]["content"])
    with pytest.raises(muse.MuseAsmError) as ei:
        muse.lint_asm(asm)
    assert "label" in str(ei.value).lower()


def test_lint_rejects_comma_operands(muse):
    res = _fixture_json("h5_response_comma.json")
    asm = muse.extract_asm(res["choices"][0]["message"]["content"])
    with pytest.raises(muse.MuseAsmError) as ei:
        muse.lint_asm(asm)
    assert "space" in str(ei.value).lower()


def test_lint_accepts_reference_corpus_asm(muse, corpus):
    """The linter must never reject the transpiler's reference asm."""
    for case in corpus["cases"]:
        findings = muse.lint_asm(case["reference_asm"])
        assert findings == []


# ----------------------------------------------------------------- extract --

def test_extract_asm_fenced_and_raw(muse):
    res = _fixture_json("h5_response_sum_match.json")
    content = res["choices"][0]["message"]["content"]
    assert muse.extract_asm(content).startswith("# Transpiled")
    raw = "LDI r1 5\nHALT\n"
    assert muse.extract_asm(raw) == raw
    with pytest.raises(muse.MuseAsmError):
        muse.extract_asm("no assembly here at all")


# --------------------------------------------------------- instruction match

def test_instruction_level_match_exact(muse, corpus):
    """Recorded Muse response carrying the reference asm matches it
    instruction-for-instruction after normalization."""
    ref = corpus["cases"][0]["reference_asm"]
    res = _fixture_json("h5_response_sum_match.json")
    cand = muse.extract_asm(res["choices"][0]["message"]["content"])
    assert muse.instruction_level_match(cand, ref) is True


def test_instruction_level_match_detects_wrong_program(muse, corpus):
    ref = corpus["cases"][0]["reference_asm"]
    res = _fixture_json("h5_response_sum_wrong.json")
    cand = muse.extract_asm(res["choices"][0]["message"]["content"])
    assert muse.instruction_level_match(cand, ref) is False


def test_pipeline_end_to_end_recorded_response(muse, corpus):
    """Full v1 pipeline offline: prompt -> chat -> extract -> lint ->
    instruction-level match, through the Meta client with a fake transport."""
    calls = []
    client = _client_factory(muse, calls)
    case = corpus["cases"][0]
    result = muse.generate_and_verify(client, case["description"],
                                      reference_asm=case["reference_asm"])
    assert result["match"] is True
    assert result["lint_clean"] is True
    assert calls and "chat/completions" in calls[0]


# -------------------------------------------------------- execution / canvas

def test_corpus_ground_truth_reexecutes(muse, corpus):
    """Every committed corpus case still executes to its recorded ground
    truth on the Glyph engine (the fixture is measured, not vibes)."""
    for case in corpus["cases"]:
        placed = muse.place_on_canvas(case["reference_asm"])
        run = muse.execute_canvas(placed)
        assert run["halted"] is True
        assert run["a0"] == case["ground_truth"]["glyph_result"]
        assert run["a0"] == case["ground_truth"]["native_result"]


def test_handwritten_asm_places_and_hits_ground_truth(muse, corpus):
    asm = _fixture("h5_handwritten_sum.asm")
    placed = muse.place_on_canvas(asm)
    run = muse.execute_canvas(placed)
    assert run["halted"] is True
    assert run["a0"] == corpus["cases"][0]["ground_truth"]["glyph_result"]


def test_semantically_wrong_program_detected_by_execution(muse, corpus):
    """A convention-clean but wrong program must FAIL the ground truth."""
    res = _fixture_json("h5_response_sum_wrong.json")
    asm = muse.extract_asm(res["choices"][0]["message"]["content"])
    muse.lint_asm(asm)  # convention-clean
    placed = muse.place_on_canvas(asm)
    run = muse.execute_canvas(placed)
    assert run["a0"] != corpus["cases"][0]["ground_truth"]["glyph_result"]


def test_corpus_score(muse, corpus):
    """Receipt metric: corpus score against recorded Muse responses."""
    score = muse.corpus_score(
        corpus,
        {c["name"]: _fixture_json(f"h5_response_{c['name']}_match.json")
         for c in corpus["cases"] if c["name"] == "sum"})
    assert score["exact_match"] == 1
    assert score["executed"] == len(corpus["cases"])


